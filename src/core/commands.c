#include "commands.h"

/* Unlisted commands consume X if evaluated, matching the error boundary.
 * DROP implies a Y operand; READ_Y covers operations that retain both levels.
 * LINK and BASE resolve their value-dependent operand counts in value_eval(). */
static const uint8_t traits[CMD_COUNT] = {
    [CMD_DIGIT] = COMMAND_ENTRY,
    [CMD_DOT] = COMMAND_ENTRY,
    [CMD_EE] = COMMAND_ENTRY,
    [CMD_CHS] = COMMAND_ENTRY,
    [CMD_BACKSPACE] = COMMAND_ENTRY,
    [CMD_CLEAR] = COMMAND_ENTRY,
    [CMD_ADD] = COMMAND_DROP,
    [CMD_SUB] = COMMAND_DROP,
    [CMD_MUL] = COMMAND_DROP,
    [CMD_DIV] = COMMAND_DROP,
    [CMD_POW] = COMMAND_DROP,
    [CMD_PI] = COMMAND_NO_X,
    [CMD_E] = COMMAND_NO_X,
    [CMD_XROOT_Y] = COMMAND_DROP,
    [CMD_LOG_BASE] = COMMAND_DROP,
    [CMD_GCD] = COMMAND_DROP,
    [CMD_LCM] = COMMAND_DROP,
    [CMD_MOD] = COMMAND_DROP,
    [CMD_MIN] = COMMAND_DROP,
    [CMD_MAX] = COMMAND_DROP,
    [CMD_COMB] = COMMAND_DROP,
    [CMD_PERM] = COMMAND_DROP,
    [CMD_ATAN2] = COMMAND_DROP,
    [CMD_PERCENT] = COMMAND_READ_Y,
    [CMD_PERCENT_CHANGE] = COMMAND_READ_Y,
    [CMD_TO_REC] = COMMAND_READ_Y | COMMAND_PAIR,
    [CMD_TO_POL] = COMMAND_READ_Y | COMMAND_PAIR,
    [CMD_HMS_ADD] = COMMAND_DROP,
    [CMD_HMS_SUB] = COMMAND_DROP,
    [CMD_RECORD_OPEN] = COMMAND_ENTRY,
    [CMD_RECORD_TAG] = COMMAND_ENTRY,
    [CMD_ALPHA_LETTER] = COMMAND_ENTRY,
    [CMD_TVM_VAR] = COMMAND_NO_X,
    [CMD_STAT_PLUS] = COMMAND_READ_Y | COMMAND_STAT,
    [CMD_STAT_MINUS] = COMMAND_READ_Y | COMMAND_STAT,
    [CMD_STAT_SUM] = COMMAND_NO_X | COMMAND_PAIR | COMMAND_STAT,
    [CMD_STAT_MEAN] = COMMAND_NO_X | COMMAND_PAIR | COMMAND_STAT,
    [CMD_STAT_WMEAN] = COMMAND_NO_X | COMMAND_PAIR | COMMAND_STAT,
    [CMD_STAT_SDEV] = COMMAND_NO_X | COMMAND_PAIR | COMMAND_STAT,
    [CMD_STAT_SCOV] = COMMAND_NO_X | COMMAND_STAT,
    [CMD_STAT_PDEV] = COMMAND_NO_X | COMMAND_PAIR | COMMAND_STAT,
    [CMD_STAT_PCOV] = COMMAND_NO_X | COMMAND_STAT,
    [CMD_FIT_X] = COMMAND_STAT,
    [CMD_FIT_Y] = COMMAND_STAT,
    [CMD_FIT_SLOPE] = COMMAND_NO_X | COMMAND_STAT,
    [CMD_FIT_INTERCEPT] = COMMAND_NO_X | COMMAND_STAT,
    [CMD_FIT_CORR] = COMMAND_NO_X | COMMAND_STAT,
    [CMD_FIT_BEST] = COMMAND_NO_X | COMMAND_STAT,
    [CMD_COMPLEX_RECT_ENTRY] = COMMAND_ENTRY,
    [CMD_COMPLEX_POLAR_ENTRY] = COMMAND_ENTRY,
    [CMD_COMPLEX_LINK] = COMMAND_DROP,
};

uint8_t command_flags(calc_cmd_t cmd)
{
    return (unsigned)cmd < CMD_COUNT ? traits[cmd] : 0;
}
