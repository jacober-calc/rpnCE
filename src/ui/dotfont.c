/* Comma: 1 column, a dot on the baseline and one just below it. */
static const uint8_t comma_rows[DOT_ROWS + 1] = { 0, 0, 0, 0, 0, 0, 0x10, 0x10 };

/* Small exponent E: 4 columns by 5 rows, centered vertically. */
static const uint8_t small_e_rows[5] = { 0x1e, 0x10, 0x1c, 0x10, 0x1e };
#define SMALL_E_WIDTH 4

static const glyph_t *find_glyph(char ch)
{
    if ((uint8_t)ch == MSYM_TIMES)
        ch = '*';
    for (unsigned i = 0; i < sizeof glyphs / sizeof glyphs[0]; i++)
        if (glyphs[i].ch == ch)
            return &glyphs[i];
    return NULL;
}

static int is_mark(char ch)
{
    return ch == '.' || ch == ',';
}

/* An exponent E comes right after a digit or a decimal mark ("1.5E-3");
 * the E in a word like ENG does not. */
static int is_exponent_e(const char *s, const char *start)
{
    if (*s != 'E' || s == start)
        return 0;
    char prev = s[-1];
    return (prev >= '0' && prev <= '9') || is_mark(prev);
}

/* Columns a character takes, not counting the gap after it. */
static int columns_of(const char *s, const char *start)
{
    if (is_exponent_e(s, start))
        return SMALL_E_WIDTH;
    if (*s == ',')
        return 1;
    const glyph_t *g = find_glyph(*s);
    return g ? g->width : 5;
}

int dot_width(const char *s)
{
    const char *start = s;
    int cols = 0;
    for (; *s; s++)
        cols += columns_of(s, start) + 1;       /* one blank column between */
    if (cols == 0)
        return 0;
    return (cols - 1) * DOT_PITCH_X;
}

static void draw_rows_pitch(const uint8_t *rows, int nrows, int x, int y,
                            int clip_left, int px_w, int px_h);

static void draw_rows(const uint8_t *rows, int nrows, int x, int y, int clip_left)
{
    draw_rows_pitch(rows, nrows, x, y, clip_left, DOT_PITCH_X, DOT_PITCH_Y);
}

static void draw_rows_pitch(const uint8_t *rows, int nrows, int x, int y,
                            int clip_left, int px_w, int px_h)
{
    for (int r = 0; r < nrows; r++) {
        uint8_t bits = rows[r];
        for (int c = 0; bits; c++, bits = (uint8_t)(bits << 1) & 0x1f) {
            if (!(bits & 0x10))
                continue;
            int px = x + c * px_w;
            if (px >= clip_left)
                gfx_FillRectangle(px, y + r * px_h, px_w, px_h);
        }
    }
}

void dot_draw(const char *s, int x, int y, uint8_t color, int clip_left)
{
    const char *start = s;
    gfx_SetColor(color);

    for (; *s; s++) {
        if (is_exponent_e(s, start)) {
            draw_rows(small_e_rows, 5, x, y + DOT_PITCH_Y, clip_left);
        } else if (*s == ',') {
            draw_rows(comma_rows, DOT_ROWS + 1, x, y, clip_left);
        } else {
            const glyph_t *g = find_glyph(*s);
            if (g)
                draw_rows(g->rows, DOT_ROWS, x, y, clip_left);
        }
        x += (columns_of(s, start) + 1) * DOT_PITCH_X;
    }
}

void dot_draw_small(const char *s, int x, int y, uint8_t color)
{
    const char *start = s;
    gfx_SetColor(color);
    for (; *s; s++) {
        const glyph_t *g = find_glyph(*s);
        if (g)
            draw_rows_pitch(g->rows, DOT_ROWS, x, y, 0, DOT_SMALL_PITCH, DOT_SMALL_PITCH);
        x += (columns_of(s, start) + 1) * DOT_SMALL_PITCH;
    }
}
